/**
 * Self-host the multilingual web fonts (JA / ZH / RU — two popular families
 * each) from Google Fonts. CJK families come as ~120 unicode-range SLICES, so
 * the browser only downloads the slices a page actually uses; RU families come
 * as latin/cyrillic subset files.
 *
 * Downloads every slice to public/fonts/g/ and regenerates
 * src/generated-fonts.css (imported from main.tsx). Re-run to refresh:
 *   node scripts/fetch-i18n-fonts.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const OUT_DIR = join(ROOT, 'public', 'fonts', 'g');
const CSS_OUT = join(ROOT, 'src', 'generated-fonts.css');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const FAMILIES = [
  { name: 'Noto Sans JP', slug: 'noto-sans-jp' },
  { name: 'M PLUS Rounded 1c', slug: 'm-plus-rounded-1c' },
  { name: 'Noto Sans SC', slug: 'noto-sans-sc' },
  { name: 'ZCOOL KuaiLe', slug: 'zcool-kuaile' },
  { name: 'PT Sans', slug: 'pt-sans' },
  { name: 'Rubik', slug: 'rubik' },
];

mkdirSync(OUT_DIR, { recursive: true });

const cssParts = [
  '/* GENERATED by scripts/fetch-i18n-fonts.mjs — do not edit by hand.',
  '   Self-hosted Google Fonts (OFL) for JA/ZH/RU: unicode-range slices so the',
  '   browser fetches only what the page uses. */',
];

let fileCount = 0;
let byteCount = 0;

for (const fam of FAMILIES) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=${fam.name.replace(/ /g, '+')}:wght@400&display=swap`;
  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': UA } })).text();
  // Subset blocks carry a /* latin */-style comment; CJK slice blocks carry
  // NONE (their url ends .NN.woff2) — so match every @font-face block and
  // label it from the comment, the url's slice number, or a running index.
  const re = /(?:\/\* ([\w[\]-]+) \*\/\s*)?@font-face\s*\{([^}]+)\}/g;
  const jobs = [];
  let idx = 0;
  for (const m of css.matchAll(re)) {
    const body = m[2];
    const url = /url\((https:[^)]+\.woff2)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim();
    if (!url || !range) continue;
    const slice = /\.(\d+)\.woff2$/.exec(url)?.[1];
    const label = m[1]?.replace(/[[\]]/g, '') ?? (slice != null ? `s${slice}` : `i${idx}`);
    idx += 1;
    jobs.push({ url, range, file: `${fam.slug}-${label}.woff2` });
  }
  // Download with modest parallelism.
  for (let i = 0; i < jobs.length; i += 12) {
    await Promise.all(jobs.slice(i, i + 12).map(async (j) => {
      const buf = Buffer.from(await (await fetch(j.url, { headers: { 'User-Agent': UA } })).arrayBuffer());
      writeFileSync(join(OUT_DIR, j.file), buf);
      fileCount += 1;
      byteCount += buf.length;
    }));
  }
  for (const j of jobs) {
    cssParts.push(
      `@font-face { font-family: '${fam.name}'; font-style: normal; font-weight: 400; font-display: swap; src: url('/fonts/g/${j.file}') format('woff2'); unicode-range: ${j.range}; }`,
    );
  }
  console.log(`${fam.name}: ${jobs.length} slices`);
}

writeFileSync(CSS_OUT, cssParts.join('\n') + '\n');
console.log(`total: ${fileCount} files, ${(byteCount / 1024 / 1024).toFixed(1)} MB → public/fonts/g + src/generated-fonts.css`);
